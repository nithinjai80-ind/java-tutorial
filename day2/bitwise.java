package day2;

public class bitwise {
    public static  void main(String[] args){
        int a=9;
        int b=4;
        System.out.println(a&b);
        System.out.println(a|b);
        System.out.println(a^b);
        System.out.println(a<<b);
        System.out.println(a>>3);
        System.out.println(5<<1);
    }
}
